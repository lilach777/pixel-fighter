/**
 * Generates docs that must stay in sync with code/data:
 *   docs/MOVES.md              — per-character move properties from the roster
 *   docs/ANIMATION_MAPPING.md  — animation -> sprite frame mapping from sprite metadata
 *   docs/asset-audit-data.md   — per-sheet processing statistics
 * Usage: npx tsx scripts/generate-docs.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROSTER } from '../shared/src/characters/roster';
import type { MoveSlot } from '../shared/src/characters/types';
import { METADATA_DIR, ROOT } from './lib/sheets';

const slots: [MoveSlot, string][] = [
  ['lp', 'LP'],
  ['hp', 'HP'],
  ['lk', 'LK'],
  ['hk', 'HK'],
  ['crLk', 'Down+LK'],
  ['launcher', 'Down+HK'],
  ['airPunch', 'Air LP/HP'],
  ['airKick', 'Air LK/HK'],
  ['special', 'SP'],
  ['specialAlt', 'Down+SP'],
  ['super', 'SU (100 meter)'],
];

// ------------------------------------------------------------------ MOVES.md
let moves = `# Move List & Frame Data\n\n_Generated by \`scripts/generate-docs.ts\` from \`shared/src/characters/roster.ts\`. Do not edit by hand._\n\n`;
moves += `Frame data is in 60 Hz frames. **Startup** = frame the first hitbox appears; **Active** = frames the hitbox is out; **Recovery** = frames after. Damage is out of the character's health (≈1000). Multi-hit moves split damage evenly. Combo damage scaling: 100%, 100%, 85%, 72%, 62%, 52%, 45%, 40%, 35%, then 30%.\n\n`;
moves += `Levels: **high** whiffs on crouchers' shorter hurtbox, **mid** blocks either way, **low** must be crouch-blocked, **overhead** must be stand-blocked.\n\n`;
moves += `These are fictional gameplay designs inspired by the sprite artwork, not statements about real people.\n\n`;
for (const c of ROSTER) {
  const s = c.stats;
  moves += `## ${c.name} — ${c.archetype}\n\n_${c.tagline}_ · Difficulty: ${c.difficulty} · Health ${s.maxHealth} · Walk ${s.walkSpeed} · Dash ${s.dashSpeed} · Jump ${s.jumpVelocity} · Super: **${c.superName}**\n\n`;
  moves += `| Input | Move | Startup | Active | Recovery | Damage | Chip | Hitstun | Blockstun | Level | Hits | Properties |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const [slot, input] of slots) {
    const m = c.moves[slot];
    const dmg = m.projectile ? `${m.projectile.damage} (projectile)` : String(m.damage);
    const props: string[] = [];
    if (m.projectile) props.push(`projectile spd ${m.projectile.speed}${m.projectile.hits ? `, ${m.projectile.hits} hits` : ''}`);
    if (m.knockdown) props.push('knockdown');
    if (m.launch) props.push(`launch ${m.launch}`);
    if (m.invuln) props.push(`invuln ${m.invuln}f`);
    if (m.armor) props.push('armor (1 hit)');
    if (m.counter) props.push('counter stance');
    if (m.advance) props.push(`advances ${m.advance}px/f`);
    if (m.rise) props.push('rising');
    if (m.cancelInto?.length) props.push(`cancel→${m.cancelInto.join('/')} f${m.cancelWindow?.[0]}-${m.cancelWindow?.[1]}`);
    moves += `| ${input} | ${m.name} | ${m.startup} | ${m.active} | ${m.recovery} | ${dmg} | ${m.projectile ? m.projectile.chip : m.chip} | ${m.projectile ? m.projectile.hitstun : m.hitstun} | ${m.projectile ? m.projectile.blockstun : m.blockstun} | ${m.level} | ${m.hits ?? m.projectile?.hits ?? 1} | ${props.join('; ')} |\n`;
  }
  moves += `\n`;
}
const balance = path.join(ROOT, 'docs', 'balance-sim.txt');
if (fs.existsSync(balance)) {
  moves += `## Balance check (AI vs AI)\n\nOutput of \`npx tsx scripts/simulate.ts 6 normal\` — every ordered pair of different characters, 6 matches each, Normal AI on both sides. This is a smoke test for gross imbalance, **not** a measure of human-level balance.\n\n\`\`\`\n${fs.readFileSync(balance, 'utf8').split('\n').slice(0, 10).join('\n')}\n\`\`\`\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'MOVES.md'), moves);

// ------------------------------------------------------------------ ANIMATION_MAPPING.md
interface Meta {
  id: string;
  source: string;
  rows: Record<string, number>;
  frames: { key: string }[];
  animations: Record<string, { frames: string[]; ticks: number[]; loop: boolean; phases?: string[]; note?: string }>;
  background: { checkerTones: number[]; pocketsRemoved: number; pocketsKept: number; floodRemoved: number; stats: { lo: number; hi: number; maxChroma: number } };
}
const metas: Meta[] = ROSTER.map((c) => JSON.parse(fs.readFileSync(path.join(METADATA_DIR, `${c.id}.json`), 'utf8')));
const animMap = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'animation-map.json'), 'utf8'));

let anim = `# Animation Mapping\n\n_Generated by \`scripts/generate-docs.ts\` from \`client/public/assets/characters/metadata/*.json\` (built by \`npm run assets:process\` from \`scripts/animation-map.json\`). Do not edit by hand._\n\n`;
anim += `Frame keys are \`rRcC\`: row R, column C (left→right) as detected by the slicer on each sheet. Labelled previews showing every key: \`docs/asset-previews/<id>-frames.png\`.\n\n`;
anim += `## Shared sheet layout\n\nAll roster sheets follow the same six-row template (frame counts differ per sheet):\n\n| Row | Content | Used for |\n|---|---|---|\n| r0 | front idle (2), side walk cycle (7–8), back view (2–4) | portrait, walk, walk-back (reversed), back-dash |\n| r1 | run cycle (8–9) with dust | forward dash, jump mid-air pose |\n| r2 | guard stance (2), punches with fire arcs (3), blast punches (2) — Migo: sword | idle stance, LP, HP, special, air punch, block |\n| r3 | weapon/kick attacks: bat (Rick/Jeremy/JCV), chainsaw (Koala), sword (Migo), kicks (others); ground burst; spin super; ready | LK, HK, launcher, air kick, super |\n| r4 | crouch (2), crawl/fall (3), knocked down with stars (3–4), get-up | crouch, hurt, knockdown, dizzy (KO), get-up |\n| r5 | emotes: point, thumbs-up, ?, !, cheer, celebrate with stars, music, drink, sleep | intro taunt, victory, time-over loss |\n\n`;
anim += `## Derived / generated animations (no dedicated art on the sheets)\n\n| Animation | How it is produced |\n|---|---|\n`;
for (const [name, spec] of Object.entries(animMap.template as Record<string, { note?: string }>)) {
  if (spec.note && /derived/i.test(spec.note)) anim += `| ${name} | ${spec.note} |\n`;
}
anim += `| hit flash | Engine draws a white tint over the current frame (original effect). |\n| projectiles | Procedural pixel fireballs / crescent / spark spray drawn by the renderer (original effects); the sheets' fire-arc punch frames play as the launch animation. |\n| hit sparks, block shield, dust, super rays | Procedural original effects (client/src/game/rendering/effects.ts). |\n\n`;
anim += `Mirroring: every sheet faces right; fighters facing left are drawn mirrored (text on clothing therefore appears mirrored for the right-side player).\n\n`;
for (const m of metas) {
  const c = ROSTER.find((r) => r.id === m.id)!;
  anim += `## ${c.name} (\`${m.source}\`)\n\nFrames per row: ${Object.entries(m.rows).map(([r, n]) => `${r}=${n}`).join(', ')} (${m.frames.length} total).\n\n`;
  const notes: string[] = animMap.characters[m.id]?.notes ?? [];
  for (const n of notes) anim += `> ${n}\n`;
  if (notes.length) anim += `\n`;
  anim += `| Animation | Frames | Ticks | Loop | Phases | Note |\n|---|---|---|---|---|---|\n`;
  for (const [name, a] of Object.entries(m.animations)) {
    anim += `| ${name} | ${a.frames.join(' ')} | ${a.ticks.join(',')} | ${a.loop ? 'yes' : ''} | ${a.phases ? a.phases.map((p) => p[0].toUpperCase()).join('') : ''} | ${a.note ?? ''} |\n`;
  }
  anim += `\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'ANIMATION_MAPPING.md'), anim);

// ------------------------------------------------------------------ asset audit data
let audit = `| Character | Source file | Size | Alpha in source | Checker tones (luma) | Frames (r0..r5) | Pockets removed / kept |\n|---|---|---|---|---|---|---|\n`;
for (const m of metas) {
  const c = ROSTER.find((r) => r.id === m.id)!;
  audit += `| ${c.name} | \`${m.source.replace('source/', '')}\` | 1536×1024 RGBA | 100% opaque (checker baked in) | ${m.background.checkerTones.join(' / ')} | ${Object.values(m.rows).join('/')} = ${m.frames.length} | ${m.background.pocketsRemoved} / ${m.background.pocketsKept} |\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'asset-audit-data.md'), audit);
console.log('docs generated');
